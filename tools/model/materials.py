# ---------------------------------------------------------------------------
REGISTRY: "OrderedDict[str, Mat]" = OrderedDict()


def add(name, **kw):
    if name in REGISTRY:
        raise ValueError(f"material {name} defined twice")
    REGISTRY[name] = Mat(name, **kw)
    return REGISTRY[name]


def lights(owner, base, color, lens_n=None, nits_on=15000.0, nits_int=30000.0, emissive=(1, 1, 1), preview=None):
    """off / on / on_intense / dmg family for a glow-mapped lamp lens."""
    common = dict(owner=owner, color=color, rough=0.04, metal=0.0, clearcoat=1.0, normal_map=lens_n)
    add(base, **common, preview=preview)
    add(base + "_on", kind="emissive", emissive=emissive, nits=nits_on, **common)
    add(base + "_on_intense", kind="emissive", emissive=emissive, nits=nits_int, **common)
    add(base + "_dmg", owner=owner, color=tuple(c * 0.35 for c in color), rough=0.5,
        normal_map=tex(owner, f"{owner}_glass_dmg_nm.normal.png"))


