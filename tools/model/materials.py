"""Material registry: one definition per material, used to

* write the BeamNG v1.5 ``*.materials.json`` files (vehicle folder + shared common folder), and
* create matching Principled-BSDF preview materials in Blender (for renders/thumbnails).

Texture references are (owner, file) pairs resolved to game paths.  Vanilla
textures that the official docs name explicitly are referenced by their game
path (see ``BUILTIN``) and never shipped.
"""
