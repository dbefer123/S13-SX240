def by_owner(owner):
    return OrderedDict((n, m) for n, m in REGISTRY.items() if m.owner == owner)


def write_json(mod_root, owner, names=None):
    """Write <folder>/main.materials.json for an owner (optionally restricted to `names`)."""
    import json
    mats = OrderedDict((n, m) for n, m in by_owner(owner).items() if m.write)
    if names is not None:
        mats = OrderedDict((n, m) for n, m in mats.items() if n in names)
    out = OrderedDict((n, m.to_json()) for n, m in mats.items())
    folder = os.path.join(mod_root, FOLDERS[owner])
    os.makedirs(folder, exist_ok=True)
    fn = "main.materials.json" if owner != "s1x" else "s1x.materials.json"
    path = os.path.join(folder, fn)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(out, f, indent=2)
        f.write("\n")
    return path


