def tex(owner, fname):
    """Game path of a texture generated into the mod."""
    return f"/{FOLDERS[owner]}/textures/{fname}"


@dataclass
class Mat:
    name: str
    owner: str = "s1x"                 # which materials.json it is written to
    color: tuple = (0.5, 0.5, 0.5)     # linear base colour factor
    rough: float = 0.5
    metal: float = 0.0
    clearcoat: float = 0.0
    cc_rough: float = 0.03
    kind: str = "solid"                # solid | paint | glass | glass_dmg | emissive | decal
    base_map: str | None = None        # game paths
    normal_map: str | None = None
    rough_map: str | None = None
    metal_map: str | None = None
    opacity_map: str | None = None
    ao_map: str | None = None
    emissive_map: str | None = None
    emissive: tuple | None = None      # emissive factor (rgb)
    nits: float = 0.0
    opacity: float = 1.0
    detail_normal: str | None = None
    detail_map: str | None = None
    detail_scale: tuple = (40, 40)
    detail_strength: float = 1.0
    double_sided: bool = False
    extra: dict = field(default_factory=dict)
    preview: tuple | None = None       # override preview colour (rgba)
    preview_tex: str | None = None     # local texture file for the preview (relative to the mod root)
    write: bool = True                 # False: glowMap key (generated by the game) - preview only

    # ------------------------------------------------------------------ json
    def stage0(self):
        s = OrderedDict()
        if self.kind == "paint":
            s["colorPaletteMap"] = BUILTIN["nullmaskR"]
            s["colorPaletteMapUseUV"] = 1
            s["instanceDiffuse"] = True
            s["clearCoatFactor"] = 1
            s["clearCoatRoughnessFactor"] = 1
            s["metallicFactor"] = 1
            s["roughnessFactor"] = 1
            s["detailNormalMap"] = BUILTIN["orange_peel"]
            s["detailNormalMapStrength"] = 0.3
            s["detailScale"] = [128, 64]
            s["normalDetailMapUseUV"] = 1
            if self.normal_map:
                s["normalMap"] = self.normal_map
            if self.ao_map:
                s["ambientOcclusionMap"] = self.ao_map
            s.update(self.extra)
            return s
        if self.base_map:
            s["baseColorMap"] = self.base_map
            if self.color != (1, 1, 1) and self.kind not in ("glass", "glass_dmg"):
                s["baseColorFactor"] = [*map(_r, self.color), 1]
        else:
            s["baseColorFactor"] = [*map(_r, self.color), 1]
        if self.normal_map:
            s["normalMap"] = self.normal_map
        if self.ao_map:
            s["ambientOcclusionMap"] = self.ao_map
        if self.rough_map:
            s["roughnessMap"] = self.rough_map
        else:
            s["roughnessFactor"] = _r(self.rough)
        if self.metal_map:
            s["metallicMap"] = self.metal_map
            s["metallicFactor"] = 1
        else:
            s["metallicFactor"] = _r(self.metal)
        if self.clearcoat:
            s["clearCoatFactor"] = _r(self.clearcoat)
            s["clearCoatRoughnessFactor"] = _r(self.cc_rough)
        if self.opacity_map:
            s["opacityMap"] = self.opacity_map
        elif self.kind in ("glass", "decal") and self.opacity < 1:
            s["opacityFactor"] = _r(self.opacity)
        if self.kind == "emissive":
            s["emissiveFactor"] = [*map(_r, self.emissive or (1, 1, 1))]
            s["emissiveIntensityNits"] = self.nits
            if self.emissive_map:
                s["emissiveMap"] = self.emissive_map
        if self.detail_normal:
            s["detailNormalMap"] = self.detail_normal
            s["detailNormalMapStrength"] = _r(self.detail_strength)
            s["detailScale"] = list(self.detail_scale)
            s["normalDetailMapUseUV"] = 1
        if self.detail_map:
            s["detailMap"] = self.detail_map
            s["detailMapUseUV"] = 1
            s["detailScale"] = list(self.detail_scale)
        s.update(self.extra)
        return s

    def to_json(self):
        m = OrderedDict()
        m["name"] = self.name
        m["mapTo"] = self.name
        m["class"] = "Material"
        m["Stages"] = [self.stage0(), {}, {}, {}]
        if self.kind in ("glass", "glass_dmg"):
            m["castShadows"] = False
            m["translucent"] = True
            m["translucentBlendOp"] = "PreMulAlpha"
            m["translucentRecvShadows"] = True
            if self.kind == "glass_dmg":
                m["alphaRef"] = 20
                m["alphaTest"] = True
        elif self.kind == "decal":
            m["translucent"] = True
            m["translucentRecvShadows"] = True
            m["translucentZWrite"] = True
        if self.double_sided:
            m["doubleSided"] = True
        m["dynamicCubemap"] = True
        m["materialTag0"] = "beamng"
        m["materialTag1"] = "vehicle"
        m["version"] = 1.5
        return m


def _r(v):
    return round(float(v), 4)


